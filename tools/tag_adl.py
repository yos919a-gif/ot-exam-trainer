def main():
    qs = [q for q in json.loads((CONTENT / "exam" / "questions.json").read_text(encoding="utf-8")) if not q.get("採点除外")]
    groups = {g["name"] for g in json.loads((CONTENT / "exam" / "diseases.json").read_text(encoding="utf-8"))["groups"]}
    unknown = sorted(set(NOTES) - groups)
    if unknown:
        raise SystemExit(f"diseases.json に無い疾患名: {unknown}")
    pats = {k: re.compile(v) for k, v in ADL.items()}
    cats = [{"name": k, "ids": []} for k in ADL]
    for q in qs:
        text = q["問題文"] + " " + " ".join(q["選択肢"])
        for c in cats:
            if pats[c["name"]].search(text):
                c["ids"].append(q["id"])
    out = {"説明": "疾患ごとの ADL（tools/tag_adl.py）", "categories": cats, "notes": NOTES}
    raw = json.dumps(out, ensure_ascii=False, indent=1).encode("utf-8")
    OUT.write_bytes(raw)
    mpath = CONTENT / "manifest.json"
    mf = json.loads(mpath.read_text(encoding="utf-8"))
    mf.setdefault("files", {})["exam/adl.json"] = {"説明": "疾患ごとの ADL（項目ごとの問題と要点）", "件数": len(cats), "bytes": len(raw),
                                                   "sha1": hashlib.sha1(raw).hexdigest()[:10]}
    mpath.write_text(json.dumps(mf, ensure_ascii=False, indent=1), encoding="utf-8")
    tagged = {i for c in cats for i in c["ids"]}
    print(f"ADL の項目 {len(cats)}・{len(tagged)} 問・要点 {len(NOTES)} 疾患 → {OUT}")


if __name__ == "__main__":
    main()
