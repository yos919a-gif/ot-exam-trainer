def move_yomi(m):
    import re
    words = re.findall(r"[^（）・、\s]+", m)
    out = []
    for w in words:
        if w in MOVE_YOMI:
            out.append(MOVE_YOMI[w])
        elif w.upper() in ("MCP", "PIP", "DIP", "IP", "MTP"):
            out.append(w.lower())
    return " ".join(out)


